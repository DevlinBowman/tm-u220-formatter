if (ENTRIES.map(([character]) => character).join("") !== PRINTABLE_ASCII) {
  throw new Error("Font A must cover printable ASCII in code-point order");
}

for (const [character, pattern] of ENTRIES) {
  const rows = pattern.split("/");
  if (rows.length !== 9 || rows.some((row) => !/^[.#]{9}$/.test(row))) {
    throw new Error(`Invalid 9-pin Font A glyph: ${JSON.stringify(character)}`);
  }
}

